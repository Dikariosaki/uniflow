-- SEGURIDAD: el navegador usa la API; nunca accede a estas tablas por PostgREST.
-- Solo se modifican permisos de tablas de UniFlow, no de otras aplicaciones.
DO $security$
DECLARE
    table_name text;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        '__EFMigrationsHistory', 'business_settings', 'categories', 'products',
        'opening_hours', 'pickup_slots', 'orders', 'order_items', 'order_events',
        'staff_roles', 'admin_audit_events'
    ]
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
        EXECUTE format('REVOKE ALL PRIVILEGES ON TABLE public.%I FROM anon, authenticated, PUBLIC', table_name);
        -- Una política restrictiva impide que una política permisiva preexistente
        -- permita el acceso desde el navegador. postgres/propietario sigue operando.
        EXECUTE format('DROP POLICY IF EXISTS uniflow_api_only ON public.%I', table_name);
        EXECUTE format(
            'CREATE POLICY uniflow_api_only ON public.%I AS RESTRICTIVE FOR ALL TO anon, authenticated USING (false) WITH CHECK (false)',
            table_name
        );
    END LOOP;
    EXECUTE format('REVOKE ALL PRIVILEGES ON SEQUENCE %s FROM anon, authenticated, PUBLIC',
                   pg_get_serial_sequence('public.business_settings', 'Id'));
END $security$;

-- STORAGE: solo fotos públicas de productos, nunca datos personales/comprobantes.
-- La creación SQL de buckets está documentada por Supabase. Los archivos se
-- cargan/actualizan/eliminan mediante su API, sin escribir storage.objects por SQL.
-- https://supabase.com/docs/guides/storage/buckets/creating-buckets
DO $storage$
DECLARE
    bucket_id text := 'uniflow-images'; -- Mismo valor que SUPABASE_PRODUCT_BUCKET.
    bucket_is_public boolean;
BEGIN
    INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    VALUES (bucket_id, bucket_id, true, 5000000, ARRAY['image/jpeg', 'image/png', 'image/webp'])
    ON CONFLICT (id) DO NOTHING;

    SELECT b.public INTO STRICT bucket_is_public
    FROM storage.buckets AS b WHERE b.id = bucket_id FOR UPDATE;

    IF bucket_is_public IS DISTINCT FROM true THEN
        RAISE EXCEPTION 'El bucket % ya existe y es privado. Elige un bucket público nuevo para el catálogo; no se cambió su visibilidad.', bucket_id;
    END IF;

    UPDATE storage.buckets AS b
    SET file_size_limit = 5000000,
        allowed_mime_types = ARRAY['image/jpeg', 'image/png', 'image/webp']
    WHERE b.id = bucket_id;

    -- Las URLs públicas permiten descargar imágenes. Esta política bloquea
    -- listado, escritura y borrado directos con JWT anon/authenticated incluso
    -- si otro bucket tiene una política permisiva general.
    -- Las cargas firmadas por la API con service_role siguen funcionando.
    -- La condición deja los demás buckets sujetos a sus propias políticas.
    EXECUTE format('DROP POLICY IF EXISTS %I ON storage.objects', 'uniflow_api_only_' || bucket_id);
    EXECUTE format(
        'CREATE POLICY %I ON storage.objects AS RESTRICTIVE FOR ALL TO anon, authenticated USING (bucket_id <> %L) WITH CHECK (bucket_id <> %L)',
        'uniflow_api_only_' || bucket_id, bucket_id, bucket_id
    );
END $storage$;

